export const formatDigits = (val, lang = "en") => {
  if (val == null) return "";
  const str = String(val);
  const map = digitMaps[lang] || digitMaps.en;
  return str.replace(/[0-9]/g, ch => map[parseInt(ch, 10)]);
};

export const weatherCodeLabel = (code, isDay = null) => {
  let isNight = false;
  if (isDay !== null && isDay !== undefined) {
    isNight = Number(isDay) === 0;
  } else {
    const hr = new Date().getHours();
    isNight = hr < 6 || hr >= 19;
  }

  if (code === 0) return isNight ? "Clear Night" : "Clear";
  if (code === 1 || code === 2) return "Partly Cloudy";
  if (code === 3) return "Overcast";
  if ([51, 53, 55, 61, 63, 65, 80, 81, 82].includes(code)) return "Rain";
  if ([71, 73, 75, 77, 85, 86].includes(code)) return "Snow";
  if ([95, 96, 99].includes(code)) return "Thunderstorm";
  if ([45, 48].includes(code)) return "Fog";
  return "Partly Cloudy";
};

