const IGNORED_LOCATION_PHRASES = new Set([
  "the next", "the morning", "the evening", "the afternoon", "the night",
  "my area", "this area", "my city", "this place", "here", "current location",
  "celsius", "fahrenheit", "km/h", "tomorrow", "today", "yesterday",
  "12 hours", "24 hours", "the week", "this week", "my location", "station"
]);

export function extractLocationSync(query) {
  if (!query || typeof query !== "string") return null;
  const lower = query.trim().toLowerCase();

  const sortedKeys = Object.keys(KNOWN_CITIES).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const regex = new RegExp(`\\b${escaped}\\b`, "i");
    if (regex.test(lower)) {
      return KNOWN_CITIES[key];
    }
  }

  const prepRegex = /\b(?:in|at|for|around|of|near|to)\b\s+([a-zA-Z\s]{2,30}?)(?:\?|\.|\!|\s+today|\s+tomorrow|\s+right now|\s+now|\s+this week|$)/i;
  const match = lower.match(prepRegex);
  if (match && match[1]) {
    const candidate = match[1].trim();
    if (!IGNORED_LOCATION_PHRASES.has(candidate) && candidate.length >= 3) {
      return { candidate };
    }
  }

  return null;
}

export async function resolveLocationAsync(query) {
  const syncMatch = extractLocationSync(query);
  if (syncMatch && syncMatch.lat !== undefined && syncMatch.lon !== undefined) {
    return syncMatch;
  }
  const candidate = syncMatch?.candidate;
  if (!candidate) return null;

  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 3500);
    const res = await fetch(`https://geocoding-api.open-meteo.com/v1/search?name=${encodeURIComponent(candidate)}&count=1&language=en&format=json`, {
      signal: controller.signal
    });
    clearTimeout(timeout);
    if (res.ok) {
      const data = await res.json();
      if (data.results && data.results.length > 0) {
        const r = data.results[0];
        const stateCountry = [r.admin1, r.country].filter(Boolean).join(", ");
        return {
          name: stateCountry ? `${r.name}, ${stateCountry}` : r.name,
          lat: r.latitude,
          lon: r.longitude
        };
      }
    }
  } catch {}

  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 3500);
    const res = await fetch(`https://nominatim.openstreetmap.org/search?q=${encodeURIComponent(candidate)}&format=json&limit=1`, {
      headers: { "User-Agent": "Atmos-Copilot-App/1.0" },
      signal: controller.signal
    });
    clearTimeout(timeout);
    if (res.ok) {
      const list = await res.json();
      if (list && list.length > 0) {
        const r = list[0];
        const segs = (r.display_name || "").split(",").map(s => s.trim()).slice(0, 3);
        return {
          name: segs.join(", ") || r.name,
          lat: parseFloat(r.lat),
          lon: parseFloat(r.lon)
        };
      }
    }
  } catch {}

  return null;
}

export async function askAiAssistant(query, lat, lon, weather, personaMode = "meteorologist") {
  const q = query.toLowerCase();

  // 1. Detect if the user specified a specific city or geographical target
  let targetCity = weather?.resolved_city || "your current coordinates";
  let targetLat = lat;
  let targetLon = lon;
  let targetWeather = weather;

  try {
    const locMatch = await resolveLocationAsync(query);
    if (locMatch && locMatch.lat !== undefined && locMatch.lon !== undefined) {
      targetCity = locMatch.name;
      targetLat = locMatch.lat;
      targetLon = locMatch.lon;
      const fetched = await fetchTelemetryData(targetLat, targetLon, targetCity);
      if (fetched && fetched.current) {
        targetWeather = fetched;
      }
    }
  } catch (err) {
    console.warn("Failed resolving target city:", err);
  }

  const city = targetCity;
  const cityNameOnly = city.split(",")[0].trim();
  const temp = targetWeather?.current?.temp ?? 26;
  const precip = targetWeather?.current?.precipitation ?? (targetWeather?.current?.precip_prob || 0);
  const humidity = targetWeather?.current?.humidity ?? 55;
  const wind = targetWeather?.current?.wind ?? 14;
  const condition = targetWeather?.current?.condition ?? "Partly Cloudy";
  const uvVal = targetWeather?.solar?.uv?.index ?? 5.2;
  const soilMoisture = targetWeather?.solar?.agro?.soilMoisture ?? "24.5";
  const rainProbToday = targetWeather?.daily?.[0]?.chance_of_rain ?? (precip > 0 ? 80 : 15);
  const rainProbTomorrow = targetWeather?.daily?.[1]?.chance_of_rain ?? 20;
  const maxTempToday = targetWeather?.daily?.[0]?.max_temp ?? temp + 2;
  const minTempToday = targetWeather?.daily?.[0]?.min_temp ?? temp - 4;
  const maxTempTomorrow = targetWeather?.daily?.[1]?.max_temp ?? temp + 1;
  const minTempTomorrow = targetWeather?.daily?.[1]?.min_temp ?? temp - 5;
  const dewPoint = (temp - ((100 - humidity) / 5)).toFixed(1);

  // 2. Query backend API if reachable
  try {
    const res = await fetch("http://localhost:5001/api/ai/ask", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        message: query,
        personaMode,
        context: {
          location: { name: city, lat: targetLat, lon: targetLon },
          weather: {
            temp,
            condition,
            humidity,
            wind,
            precipitation: precip,
            dew_point: dewPoint,
            uv: uvVal,
            uv_risk: targetWeather?.solar?.uv?.risk || "Moderate",
            uv_burn_time: targetWeather?.solar?.uv?.burnTime || "35 min",
            soil_moisture: soilMoisture,
            vpd: targetWeather?.solar?.agro?.vpd || "1.12"
          },
          daily: {
            precipitation_probability_max: targetWeather?.daily?.map(d => d.chance_of_rain || d.precip_prob || 0) || [],
            temperature_2m_max: targetWeather?.daily?.map(d => d.max_temp) || [],
            temperature_2m_min: targetWeather?.daily?.map(d => d.min_temp) || []
          },
          airQuality: {
            european_aqi: targetWeather?.aqi?.overall?.aqi || 38,
            pm2_5: targetWeather?.aqi?.pollutants?.find?.(p => p.code === 'pm2_5')?.val || 24
          }
        }
      })
    });
    if (res.ok) {
      const json = await res.json();
      if (json.answer) return json.answer;
    }
  } catch {
    // Fallback to local synthesis
  }

  // 3. Local Synthesis Fallback (Fully synchronized with resolved target city)
  if (personaMode === "travel" || q.includes("travel") || q.includes("drive") || q.includes("highway") || q.includes("route")) {
    const slick = rainProbToday > 40 || precip > 15;
    return `🚗 Highway & Travel Telemetry for ${city}:\n\n` +
      `• Road Condition: ${slick ? "Wet / Slick - Hydroplaning caution advised" : "Dry & Optimal Pavement"}\n` +
      `• Surface Wind Vectors: ${wind} km/h (Crosswind shear: Nominal)\n` +
      `• Precipitation Interception: ${rainProbToday}%\n` +
      `• Horizontal Visibility: ${humidity > 85 ? "4-7 km (Hazy/Mist)" : "> 10 km (Clear)"}\n\n` +
      `Advisory: ${slick ? `Reduce highway cruising speeds on corridors around ${cityNameOnly}.` : `Corridors across ${cityNameOnly} are optimal for smooth, high-speed transit.`}`;
  }

  if (personaMode === "agri" || q.includes("farm") || q.includes("crop") || q.includes("spray") || q.includes("soil")) {
    const canSpray = wind < 18 && rainProbToday < 30;
    return `🌾 Agro-Meteorological Advisory for ${city}:\n\n` +
      `• Topsoil Moisture: ${soilMoisture}% (Field Capacity: Optimal)\n` +
      `• Agrochemical Spraying: ${canSpray ? "✅ Optimal Window Active (Low drift & runoff risk)" : "⚠️ Caution (High drift or wash-off probability)"}\n` +
      `• Rain Probability: Today ${rainProbToday}%, Tomorrow ${rainProbTomorrow}%\n` +
      `• Thermal Load: ${temp}°C (No acute crop heat-stress warning across ${cityNameOnly})`;
  }

  if (personaMode === "outdoor" || q.includes("run") || q.includes("fitness") || q.includes("cycling") || q.includes("workout")) {
    let score = 90;
    if (temp > 33 || temp < 10) score -= 20;
    if (rainProbToday > 40) score -= 30;
    if (humidity > 75) score -= 10;
    score = Math.max(10, Math.min(100, score));

    return `🏃 Outdoor Fitness & Athletic Index for ${city}:\n\n` +
      `• Fitness Suitability Score: ${score}/100 (${score > 75 ? "Excellent" : score > 50 ? "Moderate" : "Sub-optimal"})\n` +
      `• Thermal Sensation: ${temp}°C (Relative Humidity: ${humidity}%)\n` +
      `• UV Radiation Index: ${uvVal} (Burn time: ~35-45 mins without SPF)\n` +
      `• Hydration Target: ${temp > 30 ? "650-800 ml/hr" : "400-500 ml/hr"}\n\n` +
      `Recommendation: ${score > 70 ? `Great conditions for outdoor cardio in ${cityNameOnly}.` : `Shift vigorous aerobic workouts in ${cityNameOnly} to early morning or indoors.`}`;
  }

  if (personaMode === "severe" || q.includes("storm") || q.includes("warning") || q.includes("danger") || q.includes("lightning")) {
    const stormRisk = rainProbToday > 50 || wind > 35;
    return `⚡ Severe Weather & Hazard Assessment for ${city}:\n\n` +
      `• Convective Threat Level: ${stormRisk ? "MODERATE / ELEVATED" : "LOW / MINIMAL"}\n` +
      `• Wind Gust Velocity: ${wind} km/h (Ceiling: ${wind + 10} km/h)\n` +
      `• Atmospheric Pressure Trend: Stable barometric profile\n` +
      `• Storm Precaution: ${stormRisk ? `Seek indoor shelter away from open structures in ${cityNameOnly}.` : `No immediate convective alerts active in ${cityNameOnly}.`}`;
  }

  // Domain Queries
  if (q.includes("rain") || q.includes("umbrella") || q.includes("shower") || q.includes("precipitation")) {
    return rainProbToday > 40
      ? `🌧️ Rain Alert for ${city}:\n\nPrecipitation probability is elevated at ${rainProbToday}%. Convective passing showers are likely; carrying an umbrella or rain gear in ${cityNameOnly} is strongly recommended.\n\n• Current Temp: ${temp}°C | Humidity: ${humidity}%\n• Tomorrow's Rain Outlook: ${rainProbTomorrow}%`
      : `🌧️ Rain Telemetry for ${city}:\n\nNo significant rain expected around ${cityNameOnly}. Current precipitation probability is nominal at ${rainProbToday}%.\n\n• Current Temp: ${temp}°C | Humidity: ${humidity}%\n• Tomorrow's Rain Outlook: ${rainProbTomorrow}%`;
  }

  if (q.includes("temp") || q.includes("hot") || q.includes("cold") || q.includes("warm") || q.includes("weather")) {
    return `🌡️ Thermal Analysis for ${city}:\n\nCurrent ambient reading in ${cityNameOnly} is ${temp}°C under ${condition.toLowerCase()} skies.\n\n• Diurnal Amplitude: High of ${maxTempToday}°C / Low of ${minTempToday}°C\n• Relative Humidity: ${humidity}%\n• Dew Point: ${dewPoint}°C\n• Wind Velocity: ${wind} km/h\n• Rain Probability: ${rainProbToday}%`;
  }

  if (q.includes("wind") || q.includes("breeze") || q.includes("gust")) {
    return `💨 Surface Wind Telemetry for ${city}:\n\nSurface wind velocity across ${cityNameOnly} is clocked at ${wind} km/h with nominal shear gradients.\n• Ambient Temp: ${temp}°C | Humidity: ${humidity}%`;
  }

  if (q.includes("tomorrow") || q.includes("forecast") || q.includes("week")) {
    return `📅 Synoptic Forecast for ${city}:\n\n• Tomorrow's Outlook: High of ${maxTempTomorrow}°C, Low of ${minTempTomorrow}°C\n• Rain Probability Tomorrow: ${rainProbTomorrow}%\n• Wind Stream Vectors: ~${Math.round(wind * 0.9)} km/h`;
  }

  return `☀️ Atmos Sun Copilot Briefing for ${city}:\n\nObserved surface condition in ${cityNameOnly} is ${condition} at ${temp}°C, relative humidity at ${humidity}%, and wind vectors at ${wind} km/h.\n• Diurnal Range: High ${maxTempToday}°C / Low ${minTempToday}°C\n• Rain Risk: ${rainProbToday}% Today | ${rainProbTomorrow}% Tomorrow`;
}
