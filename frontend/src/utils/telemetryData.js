export async function fetchEnvironmentalData(lat, lon) {
  const aqiUrl = `https://air-quality-api.open-meteo.com/v1/air-quality?latitude=${lat}&longitude=${lon}&current=pm10,pm2_5,european_aqi,uv_index`;
  const agroUrl = `https://api.open-meteo.com/v1/forecast?latitude=${lat}&longitude=${lon}&current=soil_moisture_0_to_1cm,vapour_pressure_deficit`;

  try {
    const [aqiRes, agroRes] = await Promise.all([fetch(aqiUrl), fetch(agroUrl)]);
    const aqiJson = aqiRes.ok ? await aqiRes.json() : null;
    const agroJson = agroRes.ok ? await agroRes.json() : null;

    const curAqi = aqiJson?.current || {};
    const curAgro = agroJson?.current || {};

    const aqiVal = curAqi.european_aqi ?? 32;
    let aqiStatus = "Good";
    let aqiColor = "emerald";
    if (aqiVal > 40 && aqiVal <= 60) {
      aqiStatus = "Moderate";
      aqiColor = "amber";
    } else if (aqiVal > 60) {
      aqiStatus = "Unhealthy";
      aqiColor = "rose";
    }

    const uvVal = curAqi.uv_index ?? 5.2;
    let uvRisk = "Low";
    if (uvVal >= 3 && uvVal < 6) uvRisk = "Moderate";
    else if (uvVal >= 6 && uvVal < 8) uvRisk = "High";
    else if (uvVal >= 8) uvRisk = "Very High";

    return {
      aqi: {
        value: aqiVal,
        status: aqiStatus,
        color: aqiColor,
        pm25: curAqi.pm2_5 ? Math.round(curAqi.pm2_5) : 18,
        pm10: curAqi.pm10 ? Math.round(curAqi.pm10) : 34
      },
      uv: {
        index: Math.round(uvVal * 10) / 10,
        risk: uvRisk,
        burnTime: uvVal > 6 ? "15-20 min" : uvVal > 3 ? "35-45 min" : "60+ min"
      },
      agro: {
        soilMoisture: curAgro.soil_moisture_0_to_1cm ? (curAgro.soil_moisture_0_to_1cm * 100).toFixed(1) : "24.5",
        vpd: curAgro.vapour_pressure_deficit ? curAgro.vapour_pressure_deficit.toFixed(2) : "1.12"
      }
    };
  } catch (err) {
    console.warn("Environmental API fallback:", err);
    return {
      aqi: { value: 32, status: "Good", color: "emerald", pm25: 18, pm10: 34 },
      uv: { index: 4.8, risk: "Moderate", burnTime: "40 min" },
      agro: { soilMoisture: "24.5", vpd: "1.12" }
    };
  }
}

